export function translate(pack: Record<string, string>, key: string, vars?: Record<string, string | number>) {
  let out = pack[key] || I18N.zh[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replace(new RegExp("\\{" + k + "\\}", "g"), String(v));
    }
  }
  return out;
}
